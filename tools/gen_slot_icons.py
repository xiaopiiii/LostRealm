def render(pattern, highlight=((2, 7), (3, 8), (5, 9))):
    rows = [r for r in pattern.strip('\n').split('\n')]
    assert len(rows) == 16, len(rows)
    img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = img.load()
    solid = [[c == '#' for c in row] for row in rows]

    def on(x, y):
        return 0 <= x < 16 and 0 <= y < 16 and solid[y][x]

    for y in range(16):
        for x in range(16):
            if not solid[y][x]:
                continue
            edge = not (on(x - 1, y) and on(x + 1, y) and on(x, y - 1) and on(x, y + 1))
            px[x, y] = DARK if edge else MID
    for x, y in highlight:
        if on(x, y) and px[x, y][:3] != DARK[:3]:
            px[x, y] = LIGHT
    return img


def main():
    tiles = []
    for name, pattern in (('weapon', WEAPON), ('shield', SHIELD),
                          ('crystal', CRYSTAL), ('contract', CONTRACT)):
        img = render(pattern)
        img.save(os.path.join(OUT_DIR, name + '.png'))
        tiles.append((name, img))
        print('wrote', name)

    for name in ('medal', 'arrow'):
        tiles.append((name, Image.open(os.path.join(OUT_DIR, name + '.png')).convert('RGBA')))

    scale, pad = 8, 8
    w = len(tiles) * (16 * scale + pad) + pad
    h = 16 * scale + pad * 2
    canvas = Image.new('RGBA', (w, h), (40, 40, 46, 255))
    x = pad
    for _n, tile in tiles:
        canvas.paste(tile.resize((16 * scale, 16 * scale), Image.NEAREST), (x, pad))
        x += 16 * scale + pad
    canvas.convert('RGB').save(PREVIEW)
    print('preview', PREVIEW)


if __name__ == '__main__':
    main()
